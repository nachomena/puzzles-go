// Computes every Circle solution with the ribs in the starting position and
// saves them in js/games/circle/engine/solutions-data.js (the other orientations are the same ones
// turned). Usage: node scripts/build-circle-solutions.mjs   (under a second)
import { writeFileSync } from 'node:fs';
import { solveAll } from '../js/games/circle/engine/solver.js';
import { ribsAt, PIECES } from '../js/games/circle/engine/pieces.js';

const bytes = [];
// 1 byte per piece, in PIECES order: side (0 = front, 1 = flipped) * 16 + turn
const count = solveAll(ribsAt(0), chosen => bytes.push(...chosen.map(({ m, s }) => (m < 0 ? 16 : 0) + s)));
const b64 = Buffer.from(Uint8Array.from(bytes)).toString('base64');
writeFileSync(new URL('../js/games/circle/engine/solutions-data.js', import.meta.url),
`/* Generated by scripts/build-circle-solutions.mjs — do not edit by hand.
   ${count} solutions with the ribs in the starting position (ribsAt(0)); per piece (in PIECES order)
   1 byte: side (0 right, 1 mirrored) * 16 + rotation. */
export const COUNT = ${count};
export const PIECE_COUNT = ${PIECES.length};
export const DATA = '${b64}';
`);
console.log(`${count} solutions, ${b64.length} characters`);
