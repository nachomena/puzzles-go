// Writes into sw.js the list of files cached for offline play and a VERSION that
// is the fingerprint of their content: any change in a file gives another version and the iPhone downloads it.
// Usage: node scripts/build-sw.mjs          updates sw.js (the pre-commit hook does it)
//      node scripts/build-sw.mjs --check  fails if sw.js is out of date (CI)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const SW = join(root, 'sw.js');
const START = '// <generated by scripts/build-sw.mjs>', END = '// </generated>';

const walk = dir => readdirSync(dir).sort().flatMap(f => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const assets = ['index.html', 'manifest.webmanifest',
  ...['css', 'js', 'fonts', 'icons'].flatMap(d => walk(join(root, d))).filter(p => !p.endsWith('.md')).map(p => relative(root, p))];

const sw = readFileSync(SW, 'utf8');
const [head, rest] = sw.split(START), [, tail] = (rest ?? '').split(END);
if (tail === undefined) throw new Error(`sw.js needs the markers "${START}" and "${END}"`);

// the fingerprint also includes the rest of sw.js, so a change in its logic counts as a new version
const hash = createHash('sha256').update(head + tail);
for (const a of assets) hash.update(a + '\0').update(readFileSync(join(root, a)));
const version = 'pzg-' + hash.digest('hex').slice(0, 10);

const lines = [];
for (const f of ['./', ...assets.map(a => './' + a)].map(f => `'${f}'`)){
  const last = lines.length - 1;
  if (last >= 0 && lines[last].length + f.length < 110) lines[last] += ', ' + f;
  else lines.push(f);
}
const block = `${START}\nconst VERSION = '${version}';\nconst FILES = [\n  ${lines.join(',\n  ')}\n];\n${END}`;
const next = head + block + tail;

if (process.argv.includes('--check')){
  if (next !== sw){
    console.error('sw.js is out of date: run  npm run build:sw');
    process.exit(1);
  }
  console.log(`sw.js up to date (${version}, ${assets.length + 1} files).`);
} else if (next !== sw){
  writeFileSync(SW, next);
  console.log(`sw.js → ${version} (${assets.length + 1} files).`);
}
