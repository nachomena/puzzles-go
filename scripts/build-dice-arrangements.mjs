// Lists every valid Dice arrangement (the 12 pieces forming 4 die faces)
// and saves them in js/games/dice/engine/arrangements-data.js.
// Usage: node scripts/build-dice-arrangements.mjs   (takes a few seconds; only needed if the pieces change)
import { writeFileSync } from 'node:fs';
import { solve } from '../js/games/dice/engine/solver.js';
import { PIECES } from '../js/games/dice/engine/pieces.js';
import { encodeArrangement, SLOTS } from '../js/games/dice/engine/codec.js';

const out = [];
const t0 = Date.now();
const res = solve({}, { limit: Infinity, onSolution: placed => out.push(encodeArrangement(placed)) });
const bytes = Uint8Array.from(out.flat());
const b64 = Buffer.from(bytes).toString('base64');
writeFileSync(new URL('../js/games/dice/engine/arrangements-data.js', import.meta.url),
`/* Generated by scripts/build-dice-arrangements.mjs — do not edit by hand.
   ${res.count} valid placements; ${SLOTS} bytes per placement (rotation * 36 + cell of each piece, in PIECES order). */
export const COUNT = ${res.count};
export const DATA = '${b64}';
`);
console.log(`${res.count} placements, ${bytes.length} bytes (${b64.length} in base64), ${Date.now() - t0} ms; pieces per placement: ${PIECES.length}`);
