// Computes every Hexagon solution and keeps one per group of solutions that are
// the same one turned or flipped (the board has 12 symmetries) in
// js/games/hexagon/engine/solutions-data.js. Uso: node scripts/build-hexagon-solutions.mjs
// (about 3 minutes; only needed if the pieces change).
import { writeFileSync } from 'node:fs';
import { solveAll } from '../js/games/hexagon/engine/solver.js';
import { PIECES, CELLS, SYMMETRIES, allPlacements } from '../js/games/hexagon/engine/pieces.js';

const pl = allPlacements(), reps = new Map();
const t0 = Date.now();
const total = solveAll(chosen => {
  const owner = new Int8Array(CELLS);
  chosen.forEach((i, p) => { for (const c of pl[p][i].cells) owner[c] = p; });
  // representative: the symmetric version with the smallest owner list
  let best = null;
  for (const perm of SYMMETRIES){
    const t = new Int8Array(CELLS);
    owner.forEach((p, c) => { t[perm[c]] = p; });
    const k = t.join();
    if (best === null || k < best) best = k;
  }
  if (!reps.has(best)) reps.set(best, chosen);
});
const bytes = [...reps.values()].flat();
const b64 = Buffer.from(Uint8Array.from(bytes)).toString('base64');
writeFileSync(new URL('../js/games/hexagon/engine/solutions-data.js', import.meta.url),
`/* Generated by scripts/build-hexagon-solutions.mjs — do not edit by hand.
   ${total} solutions in total; here ${reps.size}, one per group of solutions that are equal rotated or flipped. Per
   piece (in PIECES order) 1 byte: index of its placement in allPlacements(). */
export const TOTAL = ${total};
export const COUNT = ${reps.size};
export const PIECE_COUNT = ${PIECES.length};
export const DATA = '${b64}';
`);
console.log(`${total} solutions, ${reps.size} distinct, ${b64.length} characters, ${Date.now() - t0} ms`);
