// Generates hard Gridlock puzzles (levels 4 and 5, which would take several seconds on the spot) and
// saves them in js/games/gridlock/engine/bank-data.js. Usage:
//   node scripts/build-gridlock-bank.mjs <level> <how many> <output .json file>   (generates)
//   node scripts/build-gridlock-bank.mjs --join a.json b.json ...                    (joins and writes)
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { generateLive } from '../js/games/gridlock/engine/generator.js';
import { solve } from '../js/games/gridlock/engine/board.js';
import { runToEnd } from '../js/lib/iter.js';

/** A puzzle as text: per vehicle "<length><h|v><line><position>", e.g. "2h20" = the red one. */
const encode = p => p.cars.map((c, i) => `${c.len}${c.dir}${c.line}${p.pos[i]}`).join('');

if (process.argv[2] === '--join'){
  const all = { 4: new Set(), 5: new Set() };
  for (const f of process.argv.slice(3)) for (const [L, list] of Object.entries(JSON.parse(readFileSync(f, 'utf8')))) list.forEach(s => all[L].add(s));
  writeFileSync(new URL('../js/games/gridlock/engine/bank-data.js', import.meta.url),
`/* Generated by scripts/build-gridlock-bank.mjs — do not edit by hand.
   Precomputed hard puzzles (on the spot they would take several seconds). Each puzzle is a string with
   4 characters per vehicle: length, direction (h/v), line and position; the first is the red one. */
export const BANK = {
${Object.entries(all).map(([L, set]) => `  ${L}: [\n${[...set].map(s => `    '${s}'`).join(',\n')}\n  ]`).join(',\n')}
};
`);
  console.log(Object.fromEntries(Object.entries(all).map(([L, s]) => [L, s.size])));
} else {
  const [L, count, out] = [Number(process.argv[2]), Number(process.argv[3]), process.argv[4]];
  const data = existsSync(out) ? JSON.parse(readFileSync(out, 'utf8')) : {};
  data[L] ||= [];
  while (data[L].length < count){
    const p = runToEnd(generateLive(L));
    if (!p) continue;
    const s = solve(p.cars, p.pos);
    if (!s || s.length !== p.min) throw new Error('unverified puzzle');
    data[L].push(encode(p));
    writeFileSync(out, JSON.stringify(data));
    if (data[L].length % 10 === 0) console.log(L, data[L].length);
  }
}
