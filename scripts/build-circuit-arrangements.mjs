// Lists every valid Circuit arrangement (the 10 pieces forming paths from
// dot to dot) and saves them in js/games/circuit/engine/arrangements-data.js.
// Usage: node scripts/build-circuit-arrangements.mjs   (about 30 seconds; only if the pieces change)
import { writeFileSync } from 'node:fs';
import { solve } from '../js/games/circuit/engine/solver.js';
import { PIECES, CELLS } from '../js/games/circuit/engine/pieces.js';

const out = [];
const t0 = Date.now();
solve({}, { limit: Infinity, onSolution: placed => {
  // 2 bytes per piece, in piece order: ((side * 4 + turn) * 32 + cell)
  const byPiece = new Array(PIECES.length);
  for (const p of placed) byPiece[p.piece] = (p.face * 4 + p.rot) * CELLS + p.cell;
  out.push(...byPiece.flatMap(v => [v >> 8, v & 255]));
} });
const count = out.length / (2 * PIECES.length);
const b64 = Buffer.from(Uint8Array.from(out)).toString('base64');
writeFileSync(new URL('../js/games/circuit/engine/arrangements-data.js', import.meta.url),
`/* Generated by scripts/build-circuit-arrangements.mjs — do not edit by hand.
   ${count} valid placements; per piece (in PIECES order) 2 bytes: (side * 4 + rotation) * 32 + cell. */
export const COUNT = ${count};
export const DATA = '${b64}';
`);
console.log(`${count} placements, ${b64.length} characters, ${Date.now() - t0} ms`);
